// 3. Deterministic Shared Contour Vertex Deduplication
// ---------------------------------------------------------------------------

/**
 * Extracts inspectable contour vertices for a piece contour (`sew` or `cut`).
 *
 * Rules:
 * - Sequentially adjacent endpoints (`seg[i].p3` and `seg[(i + 1) % n].p0`) within
 *   `COINCIDENT_VERTEX_EPSILON_CM` (`1e-4 cm`) are deduplicated into ONE vertex anchored
 *   at `${pieceId}::${contour}::${nextSeg.id}::p0`, retaining BOTH incident segments.
 * - Non-coincident endpoints (open gaps > `1e-4 cm`) remain separate vertices (`seg[i]::p3`
 *   and `seg[next]::p0`) so discontinuities are never silently hidden.
 * - Segments with non-finite endpoints are skipped fail-closed and counted.
 */
export function extractContourVertices(
  pieceId: string,
  contour: CadContourKind,
  segments: readonly RenderCurveSegment[]
): { readonly vertices: readonly ExtractedContourVertex[]; readonly skippedInvalidCount: number } {
  const vertices: ExtractedContourVertex[] = [];
  let skippedInvalidCount = 0;
  const n = segments.length;
  if (n === 0) return { vertices, skippedInvalidCount };

  const validFlags = segments.map(seg => {
    const ok = isSegmentFinite(seg);
    if (!ok) skippedInvalidCount += 1;
    return ok;
  });

  // Track which segment end endpoints (p3) were absorbed by their coincident successor's p0
  const absorbedP3 = new Array<boolean>(n).fill(false);

  // First pass: check sequential adjacency (including wrap-around for closed contour if n >= 2)
  const incomingByIndex: (IncidentSegmentRef | null)[] = new Array(n).fill(null);

  for (let i = 0; i < n; i++) {
    if (!validFlags[i]) continue;
    const prevIdx = i === 0 ? (n >= 2 ? n - 1 : -1) : i - 1;
    if (prevIdx < 0 || !validFlags[prevIdx]) continue;

    const prevSeg = segments[prevIdx];
    const currSeg = segments[i];
    if (distCm(prevSeg.p3, currSeg.p0) <= COINCIDENT_VERTEX_EPSILON_CM) {
      absorbedP3[prevIdx] = true;
      incomingByIndex[i] = {
        direction: 'incoming',
        segmentId: prevSeg.id,
        segmentKind: prevSeg.kind,
        segmentRole: prevSeg.role,
        endpointSlot: 'p3',
        seamId: prevSeg.seamId
      };
    }
  }

  for (let i = 0; i < n; i++) {
    if (!validFlags[i]) continue;
    const seg = segments[i];
    const incoming = incomingByIndex[i];
    const outgoing: IncidentSegmentRef = {
      direction: 'outgoing',
      segmentId: seg.id,
      segmentKind: seg.kind,
      segmentRole: seg.role,
      endpointSlot: 'p0',
      seamId: seg.seamId
    };

    const incidentSegments: IncidentSegmentRef[] = incoming ? [incoming, outgoing] : [outgoing];

    vertices.push({
      presentationRef: buildSegmentPointRef(pieceId, contour, seg.id, 'p0'),
      pieceId,
      contour,
      segmentId: seg.id,
      endpointSlot: 'p0',
      localPointCm: { x: seg.p0.x, y: seg.p0.y },
      isSharedJunction: Boolean(incoming),
      incidentSegments
    });

    if (!absorbedP3[i]) {
      vertices.push({
        presentationRef: buildSegmentPointRef(pieceId, contour, seg.id, 'p3'),
        pieceId,
        contour,
        segmentId: seg.id,
        endpointSlot: 'p3',
        localPointCm: { x: seg.p3.x, y: seg.p3.y },
        isSharedJunction: false,
        incidentSegments: [
          {
            direction: 'incoming',
            segmentId: seg.id,
            segmentKind: seg.kind,
            segmentRole: seg.role,
            endpointSlot: 'p3',
            seamId: seg.seamId
          }
        ]
      });
    }
  }

  return { vertices, skippedInvalidCount };
}

// ---------------------------------------------------------------------------
// 4. Deterministic Segment & Cubic Bézier Closest-Point Evaluation
// ---------------------------------------------------------------------------

export function evaluateCubicBezierUnrounded(
  p0: RenderPoint2D,
  p1: RenderPoint2D,
  p2: RenderPoint2D,
  p3: RenderPoint2D,
  t: number
): RenderPoint2D {
  const mt = 1 - t;
  const mt2 = mt * mt;
  const t2 = t * t;
  return {
    x: mt2 * mt * p0.x + 3 * mt2 * t * p1.x + 3 * mt * t2 * p2.x + t2 * t * p3.x,
    y: mt2 * mt * p0.y + 3 * mt2 * t * p1.y + 3 * mt * t2 * p2.y + t2 * t * p3.y
  };
}

export function closestPointOnLineSegment(
  target: RenderPoint2D,
  a: RenderPoint2D,
  b: RenderPoint2D
): { readonly ok: true; readonly parameterT: number; readonly pointCm: RenderPoint2D; readonly distanceCm: number } | { readonly ok: false } {
  if (!isFiniteRenderPoint(target) || !isFiniteRenderPoint(a) || !isFiniteRenderPoint(b)) {
    return { ok: false };
  }
  const dx = b.x - a.x;
  const dy = b.y - a.y;
  const lenSq = dx * dx + dy * dy;
  if (!Number.isFinite(lenSq)) return { ok: false };

  let t = 0;
  if (lenSq > 0) {
    const rawT = ((target.x - a.x) * dx + (target.y - a.y) * dy) / lenSq;
    if (!Number.isFinite(rawT)) return { ok: false };
    t = Math.max(0, Math.min(1, rawT));
  }

  const pointCm: RenderPoint2D = {
    x: a.x + t * dx,
    y: a.y + t * dy
  };
  const distanceCm = distCm(target, pointCm);
  if (!isFiniteRenderPoint(pointCm) || !Number.isFinite(distanceCm)) {
    return { ok: false };
  }
  return { ok: true, parameterT: t, pointCm, distanceCm };
}

const GOLDEN_RATIO_CONJUGATE = (Math.sqrt(5) - 1) / 2;

/**
 * Deterministic closest-point evaluation on a cubic Bézier curve over t ∈ [0, 1].
 *
 * Algorithm:
 * 1. Validates all control points and query point are finite.
 * 2. Evaluates a uniform 32-interval coarse grid to collect all local-minimum brackets
 *    (preventing multi-lobe local-minimum traps).
 * 3. Refines every local-minimum bracket with 32 deterministic golden-section iterations
 *    (shrinking bracket width to < 1e-8 without derivative division hazards at Q(t) = 0).
 * 4. Fails closed (`ok: false`) if any intermediate/final evaluation is non-finite or fails
 *    monotonic consistency — NEVER silently substitutes the nearest endpoint.
 */
export function closestPointOnCubicBezier(
  target: RenderPoint2D,
  p0: RenderPoint2D,
  p1: RenderPoint2D,
  p2: RenderPoint2D,
  p3: RenderPoint2D,
  coarseSamples = 32,
  refineIterations = 32
): CubicClosestPointResult {
  if (
    !isFiniteRenderPoint(target) ||
    !isFiniteRenderPoint(p0) ||
    !isFiniteRenderPoint(p1) ||
    !isFiniteRenderPoint(p2) ||
    !isFiniteRenderPoint(p3)
  ) {
    return { ok: false, reason: 'non-finite-input' };
  }

  const n = Math.max(8, Math.floor(coarseSamples));
  const iters = Math.max(8, Math.floor(refineIterations));

  const distSqAt = (t: number): number => {
    const pt = evaluateCubicBezierUnrounded(p0, p1, p2, p3, t);
    const dx = pt.x - target.x;
    const dy = pt.y - target.y;
    return dx * dx + dy * dy;
  };

  const coarseDistSq: number[] = new Array(n + 1);
  let coarseMinSq = Number.POSITIVE_INFINITY;

  for (let i = 0; i <= n; i++) {
    const d2 = distSqAt(i / n);
    if (!Number.isFinite(d2)) {
      return { ok: false, reason: 'refinement-failed' };
    }
    coarseDistSq[i] = d2;
    if (d2 < coarseMinSq) coarseMinSq = d2;
  }

  // Collect all local-minimum indices (including endpoints 0 and n when locally minimal)
  const candidateIndices: number[] = [];
  for (let i = 0; i <= n; i++) {
    const leftOk = i === 0 || coarseDistSq[i] <= coarseDistSq[i - 1];
    const rightOk = i === n || coarseDistSq[i] <= coarseDistSq[i + 1];
    if (leftOk && rightOk) {
      candidateIndices.push(i);
    }
  }
  if (candidateIndices.length === 0) {
    return { ok: false, reason: 'refinement-failed' };
  }

  let bestT = Number.NaN;
  let bestDistSq = Number.POSITIVE_INFINITY;

  for (const idx of candidateIndices) {
    let a = Math.max(0, (idx - 1) / n);
    let b = Math.min(1, (idx + 1) / n);

    let c = b - GOLDEN_RATIO_CONJUGATE * (b - a);
    let d = a + GOLDEN_RATIO_CONJUGATE * (b - a);
    let fc = distSqAt(c);
    let fd = distSqAt(d);

    if (!Number.isFinite(fc) || !Number.isFinite(fd)) {
      return { ok: false, reason: 'refinement-failed' };
    }

    for (let k = 0; k < iters; k++) {
      if (fc <= fd) {
        b = d;
        d = c;
        fd = fc;
        c = b - GOLDEN_RATIO_CONJUGATE * (b - a);
        fc = distSqAt(c);
        if (!Number.isFinite(fc)) {
          return { ok: false, reason: 'refinement-failed' };
        }
      } else {
        a = c;
        c = d;
        fc = fd;
        d = a + GOLDEN_RATIO_CONJUGATE * (b - a);
        fd = distSqAt(d);
        if (!Number.isFinite(fd)) {
          return { ok: false, reason: 'refinement-failed' };
        }
      }
    }

    // Compare midpoint and bracket boundaries (exact endpoints t=0 or t=1 can be true minima)
    const mid = (a + b) * 0.5;
    const checks = [a, mid, b];
    for (const candT of checks) {
      const candD2 = distSqAt(candT);
      if (!Number.isFinite(candD2)) {
        return { ok: false, reason: 'refinement-failed' };
      }
      if (candD2 < bestDistSq) {
        bestDistSq = candD2;
        bestT = candT;
      }
    }
  }

  if (
    !Number.isFinite(bestT) ||
    bestT < 0 ||
    bestT > 1 ||
    !Number.isFinite(bestDistSq) ||
    bestDistSq > coarseMinSq + 1e-9
  ) {
    return { ok: false, reason: 'refinement-failed' };
  }

  const pointCm = evaluateCubicBezierUnrounded(p0, p1, p2, p3, bestT);
  const distanceCm = Math.sqrt(Math.max(0, bestDistSq));
  if (!isFiniteRenderPoint(pointCm) || !Number.isFinite(distanceCm)) {
    return { ok: false, reason: 'refinement-failed' };
  }

  return {
    ok: true,
    parameterT: bestT,
    pointCm,
    distanceCm
  };
}

