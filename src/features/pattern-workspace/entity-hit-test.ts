/**
 * UX-2.3.3.1 — Pure Read-Only Geometric Entity Identity & Mathematical Hit-Testing.
 *
 * IDENTITY & RECONCILIATION POLICY (Approved UX-2.3.3.1):
 * 1. All vertex, handle, landmark, and composite addresses generated by this module are
 *    DETERMINISTIC, NON-AUTHORITATIVE PRESENTATION REFERENCES. They are NOT authoritative
 *    upstream engineering vertex IDs.
 *    Format:
 *      - Contour segment (edge/curve): `${pieceId}::${contour}::${segmentId}`
 *      - Contour endpoint / vertex:    `${pieceId}::${contour}::${segmentId}::p0` (or `::p3`)
 *      - Bézier control handle:        `${pieceId}::${contour}::${segmentId}::p1` (or `::p2`)
 *      - Pattern notch:                `${pieceId}::notch::${notchId}`
 *      - Dart body:                    `${pieceId}::dart::${dartId}`
 *      - Dart landmark:                `${pieceId}::dart::${dartId}::apex|legLeft|legRight`
 * 2. Shared Closed-Contour Vertex Deduplication:
 *    - Sequentially adjacent segments `seg[i]` and `seg[(i + 1) % n]` within a single contour
 *      whose `seg[i].p3` and `seg[next].p0` coincide within `COINCIDENT_VERTEX_EPSILON_CM`
 *      (`1e-4 cm` = `0.001 mm`) are deduplicated into ONE shared vertex entity anchored at
 *      `${pieceId}::${contour}::${outgoingSeg.id}::p0`.
 *    - The deduplicated vertex retains explicit references to BOTH incident segments
 *      (incoming `p3` and outgoing `p0`) to support future angle inspection without
 *      performing angle calculations here.
 *    - Geometrically distinct vertices (distance > `1e-4 cm`, or non-adjacent vertices) are
 *      NEVER merged merely because they appear visually close at low zoom.
 * 3. Coordinate Purity & Immutability:
 *    - Source coordinates in `PatternArtifactBundle` are NEVER mutated and NEVER rounded
 *      before returning `localPointCm`.
 *    - Board coordinates (`boardPointCm = localPointCm + boardOffset`) are computed in full
 *      IEEE-754 float64 strictly as presentation values.
 *    - Supports both `svg-y-down` and `cartesian-y-up` via `cad-math.ts`.
 * 4. Fail-Closed Numerical Discipline:
 *    - Non-finite inputs (NaN/Infinity) or invalid camera zoom fail closed cleanly without
 *      throwing or fabricating coordinates.
 *    - Cubic Bézier closest-point evaluation uses deterministic coarse sampling + golden-section
 *      refinement and NEVER silently substitutes the nearest endpoint if refinement fails.
 */

