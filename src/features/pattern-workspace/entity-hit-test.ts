export function isFiniteRenderPoint(pt: RenderPoint2D | null | undefined): pt is RenderPoint2D {
  return (
    Boolean(pt) &&
    typeof pt!.x === 'number' &&
    typeof pt!.y === 'number' &&
    Number.isFinite(pt!.x) &&
    Number.isFinite(pt!.y)
  );
}

function isSegmentFinite(seg: RenderCurveSegment): boolean {
  if (!isFiniteRenderPoint(seg.p0) || !isFiniteRenderPoint(seg.p3)) {
    return false;
  }
  if (seg.kind === 'cubic-bezier') {
    return isFiniteRenderPoint(seg.p1) && isFiniteRenderPoint(seg.p2);
  }
  return true;
}

function unroundedBoardPoint(
  localCm: RenderPoint2D,
  offsetXCm: number,
  offsetYCm: number
): RenderPoint2D {
  return {
    x: localCm.x + offsetXCm,
    y: localCm.y + offsetYCm
  };
}

function distCm(a: RenderPoint2D, b: RenderPoint2D): number {
  return Math.hypot(b.x - a.x, b.y - a.y);
}

