// 5. Pure Mathematical Entity Hit-Testing (Zoom-Normalized & Deterministic)
// ---------------------------------------------------------------------------

function contourTieRank(entity: CadInspectableEntity): number {
  if ('contour' in entity) {
    return entity.contour === 'sew' ? 0 : 1;
  }
  return 2;
}

function compareCandidatesWithinPiece(a: EntityHitCandidate, b: EntityHitCandidate): number {
  if (a.priorityRank !== b.priorityRank) {
    return a.priorityRank - b.priorityRank;
  }
  const distDiff = a.distanceCm - b.distanceCm;
  if (Math.abs(distDiff) > 1e-9) {
    return distDiff;
  }
  const cDiff = contourTieRank(a.entity) - contourTieRank(b.entity);
  if (cDiff !== 0) return cDiff;
  return a.entity.presentationRef.localeCompare(b.entity.presentationRef);
}

/**
 * Pure read-only mathematical hit-tester for Pattern Atelier geometric entities.
 *
 * Precedence (deterministic):
 * 1. Top-most visible piece in `boardState.layerOrder` with at least one valid candidate
 *    within the zoom-normalized `hitRadiusCm` wins.
 * 2. Within that piece, priority ranks resolve overlaps deterministically:
 *    - Rank 0: Active curve's Bézier control handles (`p1`, `p2`)
 *    - Rank 1: Vertices, notches, and dart landmarks (`apex`, `legLeft`, `legRight`)
 *    - Rank 2: Straight edges, cubic curves, and dart legs
 * 3. Within the same rank: closest Euclidean cm distance, then `'sew'` before `'cut'`,
 *    then lexical `presentationRef`.
 */
export function hitTestPatternEntities(
  screenPtPx: RenderPoint2D,
  camera: CadCamera,
  projection: CadCoordinateProjection,
  artifact: PatternArtifactBundle,
  boardState: PatternBoardSnapshot,
  layerVisibility: PatternCadLayerVisibility,
  options?: EntityHitTestOptions
): EntityHitTestResult {
  const hitRadiusPx = options?.hitRadiusPx ?? DEFAULT_HIT_RADIUS_PX;
  const basePxPerCm = projection.basePxPerCm ?? BASE_PX_PER_CM;

  if (
    !isFiniteRenderPoint(screenPtPx) ||
    !Number.isFinite(camera.zoom) ||
    camera.zoom <= 0 ||
    !Number.isFinite(camera.panX) ||
    !Number.isFinite(camera.panY) ||
    !Number.isFinite(hitRadiusPx) ||
    hitRadiusPx <= 0 ||
    !Number.isFinite(basePxPerCm) ||
    basePxPerCm <= 0
  ) {
    return {
      status: 'invalid-input',
      hit: null,
      worldPtCm: null,
      hitRadiusCm: 0,
      skippedInvalidCount: 0
    };
  }

  const pxPerCm = getPixelsPerCm(camera.zoom, basePxPerCm);
  const hitRadiusCm = hitRadiusPx / pxPerCm;
  const worldPtCm = screenToWorldCm(screenPtPx, camera, projection);

  if (!isFiniteRenderPoint(worldPtCm) || !Number.isFinite(hitRadiusCm)) {
    return {
      status: 'invalid-input',
      hit: null,
      worldPtCm: null,
      hitRadiusCm: 0,
      skippedInvalidCount: 0
    };
  }

  const piecesById = new Map<string, PatternPieceRenderModel>();
  for (const p of artifact.pieces) {
    piecesById.set(p.pieceId, p);
  }

  let skippedInvalidCount = 0;
  let inspectedValidGeometryCount = 0;

  // Iterate top-most layer first (reverse of bottom-to-top render stacking order)
  for (let stackIdx = boardState.layerOrder.length - 1; stackIdx >= 0; stackIdx--) {
    const pieceId = boardState.layerOrder[stackIdx];
    if (!isPieceEffectivelyVisible(boardState, pieceId)) continue;

    const piece = piecesById.get(pieceId);
    const placement = boardState.placementsByPieceId[pieceId];
    if (!piece || !placement) continue;

    if (!Number.isFinite(placement.offsetXCm) || !Number.isFinite(placement.offsetYCm)) {
      skippedInvalidCount += 1;
      continue;
    }

    const offsetX = placement.offsetXCm;
    const offsetY = placement.offsetYCm;
    const localQuery: RenderPoint2D = {
      x: worldPtCm.x - offsetX,
      y: worldPtCm.y - offsetY
    };

    const pieceCandidates: EntityHitCandidate[] = [];

    const contoursToInspect: readonly { contour: CadContourKind; segments: readonly RenderCurveSegment[] }[] = [
      ...(layerVisibility.showSewLines
        ? [{ contour: 'sew' as const, segments: piece.sewSegments }]
        : []),
      ...(layerVisibility.showSeamAllowance
        ? [{ contour: 'cut' as const, segments: piece.cutSegments }]
        : [])
    ];

    for (const { contour, segments } of contoursToInspect) {
      // A. Deduplicated contour vertices (Rank 1)
      const extracted = extractContourVertices(piece.pieceId, contour, segments);
      skippedInvalidCount += extracted.skippedInvalidCount;

      for (const v of extracted.vertices) {
        inspectedValidGeometryCount += 1;
        const dCm = distCm(localQuery, v.localPointCm);
        if (dCm <= hitRadiusCm) {
          const entity: CadVertexEntity = {
            presentationRef: v.presentationRef,
            isAuthoritativeVertexId: false,
            entityKind: 'vertex',
            label: v.isSharedJunction
              ? `Shared Vertex (${contour.toUpperCase()})`
              : `Vertex ${v.endpointSlot.toUpperCase()} (${contour.toUpperCase()})`,
            pieceId: piece.pieceId,
            pieceCode: piece.pieceCode,
            pieceName: piece.name,
            contour,
            segmentId: v.segmentId,
            endpointSlot: v.endpointSlot,
            isSharedJunction: v.isSharedJunction,
            incidentSegments: v.incidentSegments,
            localPointCm: v.localPointCm,
            boardPointCm: unroundedBoardPoint(v.localPointCm, offsetX, offsetY)
          };
          pieceCandidates.push({
            entity,
            distanceCm: dCm,
            distancePx: dCm * pxPerCm,
            priorityRank: 1,
            layerStackIndex: stackIdx
          });
        }
      }

      // B. Segments (edges & cubic curves — Rank 2) + Active Curve Bézier Handles (Rank 0)
      for (const seg of segments) {
        if (!isSegmentFinite(seg)) {
          // Already counted in extractContourVertices
          continue;
        }
        inspectedValidGeometryCount += 1;

        if (seg.kind === 'cubic-bezier' && seg.p1 && seg.p2) {
          // Expose p1/p2 handles when this curve is currently active
          const isActiveCurve =
            options?.activeCurve?.pieceId === piece.pieceId &&
            options?.activeCurve?.contour === contour &&
            options?.activeCurve?.segmentId === seg.id;

          if (isActiveCurve) {
            const handleSpecs: readonly { slot: 'p1' | 'p2'; pt: RenderPoint2D; anchor: RenderPoint2D }[] = [
              { slot: 'p1', pt: seg.p1, anchor: seg.p0 },
              { slot: 'p2', pt: seg.p2, anchor: seg.p3 }
            ];
            for (const h of handleSpecs) {
              const dCm = distCm(localQuery, h.pt);
              if (dCm <= hitRadiusCm) {
                const entity: CadBezierHandleEntity = {
                  presentationRef: buildSegmentPointRef(piece.pieceId, contour, seg.id, h.slot),
                  isAuthoritativeVertexId: false,
                  entityKind: 'bezier-handle',
                  label: `Bézier Handle ${h.slot.toUpperCase()} (${seg.id})`,
                  pieceId: piece.pieceId,
                  pieceCode: piece.pieceCode,
                  pieceName: piece.name,
                  contour,
                  segmentId: seg.id,
                  segmentRole: seg.role,
                  seamId: seg.seamId,
                  handleSlot: h.slot,
                  localPointCm: { x: h.pt.x, y: h.pt.y },
                  boardPointCm: unroundedBoardPoint(h.pt, offsetX, offsetY),
                  anchorLocalCm: { x: h.anchor.x, y: h.anchor.y },
                  anchorBoardCm: unroundedBoardPoint(h.anchor, offsetX, offsetY)
                };
                pieceCandidates.push({
                  entity,
                  distanceCm: dCm,
                  distancePx: dCm * pxPerCm,
                  priorityRank: 0,
                  layerStackIndex: stackIdx
                });
              }
            }
          }

          // Broad-phase control-hull AABB reject (convex hull property of Bézier curves)
          const hullMinX = Math.min(seg.p0.x, seg.p1.x, seg.p2.x, seg.p3.x) - hitRadiusCm;
          const hullMaxX = Math.max(seg.p0.x, seg.p1.x, seg.p2.x, seg.p3.x) + hitRadiusCm;
          const hullMinY = Math.min(seg.p0.y, seg.p1.y, seg.p2.y, seg.p3.y) - hitRadiusCm;
          const hullMaxY = Math.max(seg.p0.y, seg.p1.y, seg.p2.y, seg.p3.y) + hitRadiusCm;
          if (
            localQuery.x >= hullMinX &&
            localQuery.x <= hullMaxX &&
            localQuery.y >= hullMinY &&
            localQuery.y <= hullMaxY
          ) {
            const closest = closestPointOnCubicBezier(localQuery, seg.p0, seg.p1, seg.p2, seg.p3);
            if (!closest.ok) {
              skippedInvalidCount += 1;
            } else if (closest.distanceCm <= hitRadiusCm) {
              const entity: CadCurveEntity = {
                presentationRef: buildSegmentRef(piece.pieceId, contour, seg.id),
                isAuthoritativeVertexId: false,
                entityKind: 'curve',
                label: `Cubic Curve · ${seg.id}`,
                pieceId: piece.pieceId,
                pieceCode: piece.pieceCode,
                pieceName: piece.name,
                contour,
                segmentId: seg.id,
                segmentKind: 'cubic-bezier',
                segmentRole: seg.role,
                seamId: seg.seamId,
                isFold: seg.isFold,
                p0LocalCm: { x: seg.p0.x, y: seg.p0.y },
                p1LocalCm: { x: seg.p1.x, y: seg.p1.y },
                p2LocalCm: { x: seg.p2.x, y: seg.p2.y },
                p3LocalCm: { x: seg.p3.x, y: seg.p3.y },
                parameterT: closest.parameterT,
                localPointCm: closest.pointCm,
                boardPointCm: unroundedBoardPoint(closest.pointCm, offsetX, offsetY)
              };
              pieceCandidates.push({
                entity,
                distanceCm: closest.distanceCm,
                distancePx: closest.distanceCm * pxPerCm,
                priorityRank: 2,
                layerStackIndex: stackIdx
              });
            }
          }
        } else {
          const minX = Math.min(seg.p0.x, seg.p3.x) - hitRadiusCm;
          const maxX = Math.max(seg.p0.x, seg.p3.x) + hitRadiusCm;
          const minY = Math.min(seg.p0.y, seg.p3.y) - hitRadiusCm;
          const maxY = Math.max(seg.p0.y, seg.p3.y) + hitRadiusCm;
          if (
            localQuery.x >= minX &&
            localQuery.x <= maxX &&
            localQuery.y >= minY &&
            localQuery.y <= maxY
          ) {
            const closest = closestPointOnLineSegment(localQuery, seg.p0, seg.p3);
            if (!closest.ok) {
              skippedInvalidCount += 1;
            } else if (closest.distanceCm <= hitRadiusCm) {
              const entity: CadEdgeEntity = {
                presentationRef: buildSegmentRef(piece.pieceId, contour, seg.id),
                isAuthoritativeVertexId: false,
                entityKind: 'edge',
                label: `Edge · ${seg.id}`,
                pieceId: piece.pieceId,
                pieceCode: piece.pieceCode,
                pieceName: piece.name,
                contour,
                segmentId: seg.id,
                segmentKind: 'line',
                segmentRole: seg.role,
                seamId: seg.seamId,
                isFold: seg.isFold,
                startLocalCm: { x: seg.p0.x, y: seg.p0.y },
                endLocalCm: { x: seg.p3.x, y: seg.p3.y },
                parameterT: closest.parameterT,
                localPointCm: closest.pointCm,
                boardPointCm: unroundedBoardPoint(closest.pointCm, offsetX, offsetY)
              };
              pieceCandidates.push({
                entity,
                distanceCm: closest.distanceCm,
                distancePx: closest.distanceCm * pxPerCm,
                priorityRank: 2,
                layerStackIndex: stackIdx
              });
            }
          }
        }
      }
    }

    // C. Notches (Rank 1)
    if (layerVisibility.showNotches) {
      for (const notch of piece.notches) {
        if (!isFiniteRenderPoint(notch.position)) {
          skippedInvalidCount += 1;
          continue;
        }
        inspectedValidGeometryCount += 1;
        const dCm = distCm(localQuery, notch.position);
        if (dCm <= hitRadiusCm) {
          const entity: CadNotchEntity = {
            presentationRef: buildNotchRef(piece.pieceId, notch.id),
            isAuthoritativeVertexId: false,
            entityKind: 'notch',
            label: notch.label ? `Notch · ${notch.label}` : `Notch · ${notch.id}`,
            pieceId: piece.pieceId,
            pieceCode: piece.pieceCode,
            pieceName: piece.name,
            notchId: notch.id,
            notchType: notch.notchType,
            notchLabel: notch.label,
            linkedSegmentId: notch.segmentId,
            parameterT: notch.parameterT,
            localPointCm: { x: notch.position.x, y: notch.position.y },
            boardPointCm: unroundedBoardPoint(notch.position, offsetX, offsetY)
          };
          pieceCandidates.push({
            entity,
            distanceCm: dCm,
            distancePx: dCm * pxPerCm,
            priorityRank: 1,
            layerStackIndex: stackIdx
          });
        }
      }
    }

    // D. Dart Landmarks (Rank 1) & Dart Legs (Rank 2)
    if (layerVisibility.showDarts) {
      for (const dart of piece.darts) {
        if (
          !isFiniteRenderPoint(dart.apex) ||
          !isFiniteRenderPoint(dart.legLeft) ||
          !isFiniteRenderPoint(dart.legRight)
        ) {
          skippedInvalidCount += 1;
          continue;
        }
        inspectedValidGeometryCount += 1;

        const landmarks: readonly { role: 'apex' | 'legLeft' | 'legRight'; pt: RenderPoint2D; name: string }[] = [
          { role: 'apex', pt: dart.apex, name: 'Dart Apex' },
          { role: 'legLeft', pt: dart.legLeft, name: 'Dart Left Leg Base' },
          { role: 'legRight', pt: dart.legRight, name: 'Dart Right Leg Base' }
        ];
        for (const lm of landmarks) {
          const dCm = distCm(localQuery, lm.pt);
          if (dCm <= hitRadiusCm) {
            const entity: CadDartLandmarkEntity = {
              presentationRef: buildDartLandmarkRef(piece.pieceId, dart.id, lm.role),
              isAuthoritativeVertexId: false,
              entityKind: 'dart-landmark',
              label: `${lm.name} · ${dart.id}`,
              pieceId: piece.pieceId,
              pieceCode: piece.pieceCode,
              pieceName: piece.name,
              dartId: dart.id,
              landmarkRole: lm.role,
              localPointCm: { x: lm.pt.x, y: lm.pt.y },
              boardPointCm: unroundedBoardPoint(lm.pt, offsetX, offsetY)
            };
            pieceCandidates.push({
              entity,
              distanceCm: dCm,
              distancePx: dCm * pxPerCm,
              priorityRank: 1,
              layerStackIndex: stackIdx
            });
          }
        }

        const leftLeg = closestPointOnLineSegment(localQuery, dart.legLeft, dart.apex);
        const rightLeg = closestPointOnLineSegment(localQuery, dart.legRight, dart.apex);
        const bestLeg =
          leftLeg.ok && rightLeg.ok
            ? leftLeg.distanceCm <= rightLeg.distanceCm
              ? leftLeg
              : rightLeg
            : leftLeg.ok
              ? leftLeg
              : rightLeg.ok
                ? rightLeg
                : null;

        if (bestLeg && bestLeg.distanceCm <= hitRadiusCm) {
          const entity: CadDartEntity = {
            presentationRef: buildDartRef(piece.pieceId, dart.id),
            isAuthoritativeVertexId: false,
            entityKind: 'dart',
            label: `Dart · ${dart.id}`,
            pieceId: piece.pieceId,
            pieceCode: piece.pieceCode,
            pieceName: piece.name,
            dartId: dart.id,
            apexLocalCm: { x: dart.apex.x, y: dart.apex.y },
            legLeftLocalCm: { x: dart.legLeft.x, y: dart.legLeft.y },
            legRightLocalCm: { x: dart.legRight.x, y: dart.legRight.y },
            widthCm: dart.widthCm,
            lengthCm: dart.lengthCm,
            localPointCm: bestLeg.pointCm,
            boardPointCm: unroundedBoardPoint(bestLeg.pointCm, offsetX, offsetY)
          };
          pieceCandidates.push({
            entity,
            distanceCm: bestLeg.distanceCm,
            distancePx: bestLeg.distanceCm * pxPerCm,
            priorityRank: 2,
            layerStackIndex: stackIdx
          });
        }
      }
    }

    // Top-most visible piece with at least one valid hit wins (layer-order precedence)
    if (pieceCandidates.length > 0) {
      pieceCandidates.sort(compareCandidatesWithinPiece);
      return {
        status: 'hit',
        hit: pieceCandidates[0],
        worldPtCm,
        hitRadiusCm,
        skippedInvalidCount
      };
    }
  }

  if (inspectedValidGeometryCount === 0 && skippedInvalidCount > 0) {
    return {
      status: 'invalid-geometry',
      hit: null,
      worldPtCm,
      hitRadiusCm,
      skippedInvalidCount
    };
  }

  return {
    status: 'miss',
    hit: null,
    worldPtCm,
    hitRadiusCm,
    skippedInvalidCount
  };
}

// ---------------------------------------------------------------------------
// 6. Artifact & Board-Placement Reconciliation (Zero Stale References)
// ---------------------------------------------------------------------------

/**
 * Revalidates an inspected entity against the active read-only `PatternArtifactBundle`
 * and current `PatternBoardSnapshot`:
 * - Returns a refreshed entity with updated unrounded source & board coordinates if
 *   its presentation reference still exists and remains finite & visible.
 * - Returns `null` if the piece, segment, notch, dart, or placement disappeared or became
 *   non-finite (zero stale entity references).
 */
export function reconcileInspectedEntityWithArtifact(
  prev: CadInspectableEntity | null,
  artifact: PatternArtifactBundle | null,
  boardState: PatternBoardSnapshot
): CadInspectableEntity | null {
  if (!prev || !artifact) return null;

  const piece = artifact.pieces.find(p => p.pieceId === prev.pieceId);
  const placement = boardState.placementsByPieceId[prev.pieceId];
  if (
    !piece ||
    !placement ||
    !isPieceEffectivelyVisible(boardState, prev.pieceId) ||
    !Number.isFinite(placement.offsetXCm) ||
    !Number.isFinite(placement.offsetYCm)
  ) {
    return null;
  }

  const offsetX = placement.offsetXCm;
  const offsetY = placement.offsetYCm;

  switch (prev.entityKind) {
    case 'vertex': {
      const segments = prev.contour === 'sew' ? piece.sewSegments : piece.cutSegments;
      const { vertices } = extractContourVertices(piece.pieceId, prev.contour, segments);
      const matched = vertices.find(v => v.presentationRef === prev.presentationRef);
      if (!matched) return null;
      return {
        ...prev,
        pieceCode: piece.pieceCode,
        pieceName: piece.name,
        isSharedJunction: matched.isSharedJunction,
        incidentSegments: matched.incidentSegments,
        localPointCm: matched.localPointCm,
        boardPointCm: unroundedBoardPoint(matched.localPointCm, offsetX, offsetY)
      };
    }

    case 'bezier-handle': {
      const segments = prev.contour === 'sew' ? piece.sewSegments : piece.cutSegments;
      const seg = segments.find(s => s.id === prev.segmentId);
      if (!seg || seg.kind !== 'cubic-bezier' || !isSegmentFinite(seg) || !seg.p1 || !seg.p2) {
        return null;
      }
      const pt = prev.handleSlot === 'p1' ? seg.p1 : seg.p2;
      const anchor = prev.handleSlot === 'p1' ? seg.p0 : seg.p3;
      return {
        ...prev,
        pieceCode: piece.pieceCode,
        pieceName: piece.name,
        segmentRole: seg.role,
        seamId: seg.seamId,
        localPointCm: { x: pt.x, y: pt.y },
        boardPointCm: unroundedBoardPoint(pt, offsetX, offsetY),
        anchorLocalCm: { x: anchor.x, y: anchor.y },
        anchorBoardCm: unroundedBoardPoint(anchor, offsetX, offsetY)
      };
    }

    case 'edge': {
      const segments = prev.contour === 'sew' ? piece.sewSegments : piece.cutSegments;
      const seg = segments.find(s => s.id === prev.segmentId);
      if (!seg || seg.kind !== 'line' || !isSegmentFinite(seg)) {
        return null;
      }
      const t = Number.isFinite(prev.parameterT) ? Math.max(0, Math.min(1, prev.parameterT)) : 0.5;
      const pt: RenderPoint2D = {
        x: seg.p0.x + (seg.p3.x - seg.p0.x) * t,
        y: seg.p0.y + (seg.p3.y - seg.p0.y) * t
      };
      return {
        ...prev,
        pieceCode: piece.pieceCode,
        pieceName: piece.name,
        segmentRole: seg.role,
        seamId: seg.seamId,
        isFold: seg.isFold,
        startLocalCm: { x: seg.p0.x, y: seg.p0.y },
        endLocalCm: { x: seg.p3.x, y: seg.p3.y },
        parameterT: t,
        localPointCm: pt,
        boardPointCm: unroundedBoardPoint(pt, offsetX, offsetY)
      };
    }

    case 'curve': {
      const segments = prev.contour === 'sew' ? piece.sewSegments : piece.cutSegments;
      const seg = segments.find(s => s.id === prev.segmentId);
      if (!seg || seg.kind !== 'cubic-bezier' || !isSegmentFinite(seg) || !seg.p1 || !seg.p2) {
        return null;
      }
      const t = Number.isFinite(prev.parameterT) ? Math.max(0, Math.min(1, prev.parameterT)) : 0.5;
      const pt = evaluateCubicBezierUnrounded(seg.p0, seg.p1, seg.p2, seg.p3, t);
      if (!isFiniteRenderPoint(pt)) return null;
      return {
        ...prev,
        pieceCode: piece.pieceCode,
        pieceName: piece.name,
        segmentRole: seg.role,
        seamId: seg.seamId,
        isFold: seg.isFold,
        p0LocalCm: { x: seg.p0.x, y: seg.p0.y },
        p1LocalCm: { x: seg.p1.x, y: seg.p1.y },
        p2LocalCm: { x: seg.p2.x, y: seg.p2.y },
        p3LocalCm: { x: seg.p3.x, y: seg.p3.y },
        parameterT: t,
        localPointCm: pt,
        boardPointCm: unroundedBoardPoint(pt, offsetX, offsetY)
      };
    }

    case 'notch': {
      const notch = piece.notches.find(n => n.id === prev.notchId);
      if (!notch || !isFiniteRenderPoint(notch.position)) return null;
      return {
        ...prev,
        pieceCode: piece.pieceCode,
        pieceName: piece.name,
        notchType: notch.notchType,
        notchLabel: notch.label,
        linkedSegmentId: notch.segmentId,
        parameterT: notch.parameterT,
        localPointCm: { x: notch.position.x, y: notch.position.y },
        boardPointCm: unroundedBoardPoint(notch.position, offsetX, offsetY)
      };
    }

    case 'dart': {
      const dart: RenderDart | undefined = piece.darts.find(d => d.id === prev.dartId);
      if (
        !dart ||
        !isFiniteRenderPoint(dart.apex) ||
        !isFiniteRenderPoint(dart.legLeft) ||
        !isFiniteRenderPoint(dart.legRight)
      ) {
        return null;
      }
      return {
        ...prev,
        pieceCode: piece.pieceCode,
        pieceName: piece.name,
        apexLocalCm: { x: dart.apex.x, y: dart.apex.y },
        legLeftLocalCm: { x: dart.legLeft.x, y: dart.legLeft.y },
        legRightLocalCm: { x: dart.legRight.x, y: dart.legRight.y },
        widthCm: dart.widthCm,
        lengthCm: dart.lengthCm,
        localPointCm: { x: dart.apex.x, y: dart.apex.y },
        boardPointCm: unroundedBoardPoint(dart.apex, offsetX, offsetY)
      };
    }

    case 'dart-landmark': {
      const dart: RenderDart | undefined = piece.darts.find(d => d.id === prev.dartId);
      if (!dart) return null;
      const pt =
        prev.landmarkRole === 'apex'
          ? dart.apex
          : prev.landmarkRole === 'legLeft'
            ? dart.legLeft
            : dart.legRight;
      if (!isFiniteRenderPoint(pt)) return null;
      return {
        ...prev,
        pieceCode: piece.pieceCode,
        pieceName: piece.name,
        localPointCm: { x: pt.x, y: pt.y },
        boardPointCm: unroundedBoardPoint(pt, offsetX, offsetY)
      };
    }
  }
}
